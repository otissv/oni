#!/usr/bin/env python3
"""Build the complete embedded SDL GPU shader bundle offline."""

import argparse
from concurrent.futures import ThreadPoolExecutor
from contextlib import contextmanager
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent
# ID, GLSL source, SDL stage, uniform buffers, samplers. Reflection verifies counts.
SHADERS = (
    ("UI_Vertex", "ui.vert", "VERTEX", 1, 0),
    ("UI_Fragment", "ui.frag", "FRAGMENT", 0, 4),
    ("LCD_Fragment", "ui_lcd.frag", "FRAGMENT", 1, 4),
    ("Vector_Vertex", "vector.vert", "VERTEX", 1, 0),
    ("Vector_Solid_Vertex", "vector_solid.vert", "VERTEX", 1, 0),
    ("Vector_Fragment", "vector.frag", "FRAGMENT", 1, 3),
    ("Probe_Vertex", "dual_source_test.vert", "VERTEX", 0, 0),
    ("Probe_Fragment", "dual_source_test.frag", "FRAGMENT", 0, 0),
)
FORMATS = ("spv", "msl", "dxil")


class BuildError(Exception):
    pass


def artifact_name(source, fmt):
    stem, stage = source.rsplit(".", 1)
    return f"{stem}.{fmt}.{stage}"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def registry():
    lines = ["// Generated by scripts/build_shaders.py. Do not edit.", "package oni", "", "@(private)", "GPU_Shader :: enum {"]
    lines.extend(f"\t{s[0]}," for s in SHADERS)
    lines.extend(["}", "", "@(private)", "gpu_shader_assets := [GPU_Shader]GPU_Shader_Asset{"])
    for name, source, stage, uniforms, samplers in SHADERS:
        lines.extend([
            f"\t.{name} = {{",
            f'\t\tname = "{source}", stage = .{stage},',
            f"\t\tnum_uniform_buffers = {uniforms}, num_samplers = {samplers},",
        ])
        lines.extend(f'\t\t{field} = #load("shaders/{artifact_name(source, fmt)}"),' for field, fmt in (("spirv", "spv"), ("msl", "msl"), ("dxil", "dxil")))
        lines.append("\t},")
    lines.extend(["}", ""])
    return "\n".join(lines).encode()


def inputs(root):
    return {
        "builder": digest(Path(__file__).read_bytes()),
        "sources": {s[1]: digest((root / "shaders" / s[1]).read_bytes()) for s in SHADERS},
    }


def current(root, expected):
    try:
        stamp = json.loads((root / "shaders" / "compiled.json").read_text())
        if stamp["inputs"] != expected or (root / "gpu_shader_assets.odin").read_bytes() != registry():
            return False
        for shader in SHADERS:
            for fmt in FORMATS:
                name = artifact_name(shader[1], fmt)
                if stamp["artifacts"][name] != digest((root / "shaders" / name).read_bytes()):
                    return False
        return True
    except (OSError, ValueError, KeyError, TypeError):
        return False


def resolve_tool(name):
    executable = shutil.which(os.environ.get(f"ONI_{name.upper()}", name))
    if not executable:
        raise BuildError(f"{name} is required to rebuild shaders; see docs/SHADERS.md")
    return executable


def run(args):
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode:
        raise BuildError(f"{Path(args[0]).name} failed for {args[1]}:\n{result.stdout}{result.stderr}")


def compile_shader(shader, root, staging, glslc, shadercross):
    name, source, stage, uniforms, samplers = shader
    spv = staging / artifact_name(source, "spv")
    run([glslc, str(root / "shaders" / source), "-o", str(spv)])
    code = spv.read_bytes()
    if len(code) < 20 or code[:4] != bytes.fromhex("03022307") or len(code) % 4:
        raise BuildError(f"{source}: invalid SPIR-V output")
    for fmt in ("MSL", "DXIL", "JSON"):
        output = staging / artifact_name(source, fmt.lower())
        args = [shadercross, str(spv), "-s", "SPIRV", "-d", fmt, "-t", stage.lower(), "-e", "main", "-o", str(output)]
        if fmt == "MSL":
            args.extend(["--msl-version", "2.1.0"])
        run(args)
        if fmt == "MSL":
            msl = output.read_text()
            if not re.search(r"\bmain0\(", msl):
                raise BuildError(f"{source}: MSL entrypoint main0 is missing")
            if name in ("LCD_Fragment", "Probe_Fragment"):
                if any(f"[[color(0), index({i})]]" not in msl for i in (0, 1)):
                    raise BuildError(f"{source}: MSL lost dual-source blend outputs")
            # Canonical text hashes survive Windows checkouts and compiler newlines.
            output.write_bytes(msl.encode("utf-8"))
        elif fmt == "DXIL":
            dxil = output.read_bytes()
            if len(dxil) <= 32 or dxil[:4] != b"DXBC":
                raise BuildError(f"{source}: invalid DXIL output")
        else:
            metadata = json.loads(output.read_text())
            expected = {"uniform_buffers": uniforms, "samplers": samplers, "storage_buffers": 0, "storage_textures": 0}
            if any(metadata.get(key) != value for key, value in expected.items()):
                raise BuildError(f"{source}: reflected resource counts do not match SDL bindings: {metadata}")


@contextmanager
def build_lock(root):
    directory = root / "build"
    directory.mkdir(exist_ok=True)
    with (directory / "shaders.lock").open("a+b") as lock:
        if os.name == "nt":
            import msvcrt
            if os.fstat(lock.fileno()).st_size == 0:
                lock.write(b"\0")
                lock.flush()
            lock.seek(0)
            msvcrt.locking(lock.fileno(), msvcrt.LK_LOCK, 1)
        else:
            import fcntl
            fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            if os.name == "nt":
                lock.seek(0)
                msvcrt.locking(lock.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


def build(root=ROOT, *, check=False, force=False):
    with build_lock(root):
        expected = inputs(root)
        if not force and current(root, expected):
            print("Shader bundles up to date (SPIR-V, MSL, DXIL)")
            return
        if check:
            raise BuildError("Shader bundle is missing, stale or corrupt; run python3 scripts/build_shaders.py")
        glslc, shadercross = resolve_tool("glslc"), resolve_tool("shadercross")
        with tempfile.TemporaryDirectory(prefix=".staging-", dir=root / "shaders") as temp:
            staging = Path(temp)
            with ThreadPoolExecutor(max_workers=min(4, len(SHADERS))) as pool:
                # Consume every result; no publication unless every shader compiled successfully.
                list(pool.map(lambda shader: compile_shader(shader, root, staging, glslc, shadercross), SHADERS))
            if inputs(root) != expected:
                raise BuildError("Shader sources changed during compilation; retry the build")
            hashes = {artifact_name(s[1], fmt): digest((staging / artifact_name(s[1], fmt)).read_bytes()) for s in SHADERS for fmt in FORMATS}
            (staging / "gpu_shader_assets.odin").write_bytes(registry())
            (staging / "compiled.json").write_text(json.dumps({"inputs": expected, "artifacts": hashes}, indent=2, sort_keys=True) + "\n")
            for name in hashes:
                os.replace(staging / name, root / "shaders" / name)
            os.replace(staging / "gpu_shader_assets.odin", root / "gpu_shader_assets.odin")
            # The completion record is published last. An interrupted publication is stale.
            os.replace(staging / "compiled.json", root / "shaders" / "compiled.json")
        print("Built shader bundles (SPIR-V, MSL, DXIL)")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--check", action="store_true", help="verify all source and artifact hashes without invoking compilers")
    group.add_argument("--force", action="store_true", help="rebuild all formats, including after a compiler upgrade")
    args = parser.parse_args()
    try:
        build(check=args.check, force=args.force)
    except (BuildError, OSError, ValueError) as error:
        parser.exit(1, f"Shader build failed: {error}\n")


if __name__ == "__main__":
    main()
